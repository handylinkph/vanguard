import type { Plan, PlanItem, Contact } from "@/lib/types";
import { HAZARD_LABEL } from "@/content/guides";

export const esc = (s: unknown) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

/** Self-contained, printable HTML for a plan (used for print view and offline download). */
export function planBodyHtml(plan: Plan, items: PlanItem[], contacts: Contact[]) {
  const s = plan.sections ?? {};
  const list = (rows: string[]) => (rows.length ? `<ul>${rows.join("")}</ul>` : `<p class="muted">Not filled in yet.</p>`);
  const phase = (p: string) => list(items.filter((i) => i.phase === p).map((i) => `<li>${i.done ? "☑" : "☐"} ${esc(i.label)}${i.assigned_to ? ` <em>(${esc(i.assigned_to)})</em>` : ""}</li>`));
  return `
<header><h1>${esc(plan.title)}</h1>
<p class="muted">${esc(HAZARD_LABEL[plan.hazard] ?? plan.hazard)} · ${plan.plan_type === "household" ? "Household plan" : "Personal plan"} · Status: ${esc(plan.status)} · Last updated ${esc(new Date(plan.updated_at).toLocaleDateString("en-PH"))}${plan.review_on ? ` · Review by ${esc(plan.review_on)}` : ""}</p></header>
<section class="callout"><strong>In an emergency call 911.</strong> Follow instructions from your LGU, PAGASA, PHIVOLCS and NDRRMC. This plan is a personal preparedness document, not an official instruction.</section>
<h2>Meeting places</h2>
${list((s.meeting_places ?? []).map((m) => `<li><strong>${esc(m.kind === "far" ? "Outside the neighbourhood" : "Near home")}:</strong> ${esc(m.name)}${m.address ? ` — ${esc(m.address)}` : ""}</li>`))}
<h2>Evacuation destinations</h2>
${list((s.evacuation_destinations ?? []).map((e) => `<li><strong>${esc(e.name)}</strong>${e.address ? ` — ${esc(e.address)}` : ""}${e.route ? `<br/>Route: ${esc(e.route)}` : ""}${e.notes ? `<br/>${esc(e.notes)}` : ""}</li>`))}
<h2>Responsibilities</h2>
${list((s.responsibilities ?? []).map((r) => `<li><strong>${esc(r.person || "Anyone")}:</strong> ${esc(r.task)}</li>`))}
${s.special_considerations ? `<p><strong>Special considerations:</strong> ${esc(s.special_considerations)}</p>` : ""}
<h2>Communication plan</h2>
<ul>
<li><strong>Out-of-area contact:</strong> ${esc(s.communication?.out_of_area_contact || "—")}</li>
<li><strong>How we check in:</strong> ${esc(s.communication?.check_in_method || "—")}</li>
${s.communication?.code_words ? `<li><strong>Family code word:</strong> ${esc(s.communication.code_words)}</li>` : ""}
${s.communication?.notes ? `<li>${esc(s.communication.notes)}</li>` : ""}
</ul>
<h2>Emergency contacts</h2>
${list([`<li><strong>National emergency hotline:</strong> 911</li>`, ...contacts.map((c) => `<li><strong>${esc(c.name)}</strong>${c.relationship ? ` (${esc(c.relationship)})` : ""}: ${esc(c.phone)}${c.alt_phone ? ` / ${esc(c.alt_phone)}` : ""}</li>`)])}
<h2>Checklist — before</h2>${phase("before")}
<h2>During</h2>${phase("during")}
<h2>After</h2>${phase("after")}
${s.notes ? `<h2>Notes</h2><p>${esc(s.notes)}</p>` : ""}
<footer class="muted">Generated by Vanguard — “Ready at all times, all things, all places.”</footer>`;
}

export function planDocumentHtml(plan: Plan, items: PlanItem[], contacts: Contact[]) {
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"/><meta name="viewport" content="width=device-width,initial-scale=1"/>
<title>${esc(plan.title)} — Vanguard emergency plan</title>
<style>body{font-family:Inter,system-ui,sans-serif;max-width:760px;margin:24px auto;padding:0 16px;color:#0f1b2d;line-height:1.5}h1{color:#0b1f3a;margin-bottom:4px}h2{color:#0b1f3a;border-bottom:1px solid #e2e7ef;padding-bottom:4px;margin-top:24px;font-size:1.1rem}.muted{color:#5b6b82;font-size:.9rem}.callout{background:#fff4f4;border:1px solid #f3c4c4;padding:10px 12px;border-radius:8px;margin:12px 0}ul{padding-left:20px}</style>
</head><body>${planBodyHtml(plan, items, contacts)}</body></html>`;
}
