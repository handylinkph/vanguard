import { notFound } from "next/navigation";
import { requireUser } from "@/lib/auth";
import { Card, CardContent, PageHeader, Progress } from "@/components/ui";
import { PrintButton } from "@/components/ui/copy-button";
import { orgReadiness } from "@/lib/org";
import { fmtDate, daysAgoISO } from "@/lib/utils";

export const metadata = { title: "Organization readiness report" };

export default async function Report({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const { supabase } = await requireUser();
  const { data: org } = await supabase.from("organizations").select("*").eq("id", id).maybeSingle();
  if (!org) notFound();
  const yearAgo = daysAgoISO(365).slice(0, 10);
  const [plans, checklist, assignments, facilities, contacts, drills, members] = await Promise.all([
    supabase.from("org_plans").select("title, status, review_on, updated_at").eq("org_id", id),
    supabase.from("org_checklist_items").select("list_key, label, done").eq("org_id", id).order("sort"),
    supabase.from("org_assignments").select("title, status, due_on").eq("org_id", id),
    supabase.from("org_facilities").select("name, occupancy").eq("org_id", id),
    supabase.from("org_contacts").select("name, role, phone").eq("org_id", id),
    supabase.from("org_drills").select("title, drill_type, scheduled_for, completed_on, participants, evacuation_minutes").eq("org_id", id).order("scheduled_for", { ascending: false }),
    supabase.from("org_members").select("user_id", { count: "exact", head: true }).eq("org_id", id),
  ]);
  const r = orgReadiness({
    activePlans: (plans.data ?? []).filter((p) => p.status === "active").length, checklistDone: (checklist.data ?? []).filter((c) => c.done).length, checklistTotal: checklist.data?.length ?? 0,
    assignmentsDone: (assignments.data ?? []).filter((a) => a.status === "done").length, assignmentsTotal: assignments.data?.length ?? 0,
    drillsLast12m: (drills.data ?? []).filter((d) => d.completed_on && d.completed_on >= yearAgo).length, facilities: facilities.data?.length ?? 0, contacts: contacts.data?.length ?? 0,
  });
  return (
    <>
      <PageHeader title={`${org.name} — readiness report`} description={`Generated ${fmtDate(new Date().toISOString())} · ${members.count ?? 0} members`} actions={<PrintButton label="Print report" />} />
      <Card><CardContent className="prose-v pt-5 text-sm">
        <p className="text-3xl font-semibold text-navy">{r.overall}% overall readiness</p>
        <ul>{r.parts.map((p) => <li key={p.label}>{p.label}: {p.value}%</li>)}</ul>
        <Progress value={r.overall} className="no-print" />
        <h2>Plans</h2><ul>{(plans.data ?? []).map((p) => <li key={p.title}>{p.title} — {p.status}{p.review_on ? `, review by ${p.review_on}` : ""}</li>)}</ul>
        <h2>Checklists</h2><ul>{(checklist.data ?? []).map((c, i) => <li key={i}>{c.done ? "☑" : "☐"} [{c.list_key}] {c.label}</li>)}</ul>
        <h2>Assignments</h2><ul>{(assignments.data ?? []).map((a, i) => <li key={i}>{a.title} — {a.status}{a.due_on ? ` (due ${a.due_on})` : ""}</li>)}</ul>
        <h2>Drills</h2><ul>{(drills.data ?? []).map((d, i) => <li key={i}>{d.title} ({d.drill_type}) — {d.completed_on ? `completed ${d.completed_on}, ${d.participants ?? 0} participants${d.evacuation_minutes ? `, ${d.evacuation_minutes} min` : ""}` : `scheduled ${d.scheduled_for}`}</li>)}</ul>
        <h2>Facilities</h2><ul>{(facilities.data ?? []).map((f) => <li key={f.name}>{f.name}{f.occupancy ? ` — occupancy ${f.occupancy}` : ""}</li>)}</ul>
        <h2>Emergency contacts</h2><ul>{(contacts.data ?? []).map((c, i) => <li key={i}>{c.name}{c.role ? ` (${c.role})` : ""}{c.phone ? `: ${c.phone}` : ""}</li>)}</ul>
        <p className="text-xs text-muted">Completion-based readiness tracking generated by Vanguard. Not an official compliance certification.</p>
      </CardContent></Card>
    </>
  );
}
